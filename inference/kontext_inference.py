#!/usr/bin/env python3
"""
Inference script for evaluating adversarial images generated by ManifoldHijack.
Runs FLUX.1 Kontext editing on perturbed images to verify attack effectiveness.
"""

import argparse
import os
from pathlib import Path

import torch
from diffusers import FluxKontextPipeline
from PIL import Image


def parse_args():
    p = argparse.ArgumentParser(
        description="Run FLUX.1 Kontext inference on adversarial images"
    )
    p.add_argument("--model_path", type=str,
                   default="./models/FLUX.1-Kontext-dev")
    p.add_argument("--context_image", type=str, required=True,
                   help="Path to the (adversarial) context image")
    p.add_argument("--prompt", type=str, default="a person in the school",
                   help="Editing prompt")
    p.add_argument("--output_dir", type=str, default="./outputs/inference")
    p.add_argument("--guidance_scale", type=float, default=3.5)
    p.add_argument("--num_inference_steps", type=int, default=20)
    p.add_argument("--width", type=int, default=512)
    p.add_argument("--height", type=int, default=512)
    p.add_argument("--seed", type=int, default=2025)
    return p.parse_args()


def main():
    args = parse_args()
    os.makedirs(args.output_dir, exist_ok=True)

    pipe = FluxKontextPipeline.from_pretrained(
        args.model_path, torch_dtype=torch.bfloat16
    ).to("cuda")

    context_image = Image.open(args.context_image).convert("RGB")
    generator = torch.Generator("cuda").manual_seed(args.seed)


    image = pipe(
        image=context_image,
        prompt=args.prompt,
        guidance_scale=args.guidance_scale,
        width=args.width,
        height=args.height,
        max_area=args.width * args.height,
        _auto_resize=False,
        num_inference_steps=args.num_inference_steps,
        generator=generator,
    ).images[0]

    stem = Path(args.context_image).stem
    output_path = os.path.join(args.output_dir, f"{stem}_output.png")
    image.save(output_path)
    print(f"Saved: {output_path}")


if __name__ == "__main__":
    main()
